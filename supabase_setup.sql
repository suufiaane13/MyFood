-- ── Catégories ────────────────────────────────────────────────────────────────
create policy "categories_select_public" on public.categories
  for select using (true);

create policy "categories_admin_all" on public.categories
  for all
  using   (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- ── Plats ─────────────────────────────────────────────────────────────────────
create policy "plats_select_public" on public.plats
  for select using (true);

create policy "plats_admin_insert" on public.plats
  for insert
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

create policy "plats_admin_update" on public.plats
  for update
  using   (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

create policy "plats_admin_delete" on public.plats
  for delete
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- ── Profils ───────────────────────────────────────────────────────────────────
create policy "profiles_select_own" on public.profiles
  for select using (auth.uid() = id);

create policy "profiles_update_own" on public.profiles
  for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "profiles_insert_own" on public.profiles
  for insert with check (auth.uid() = id);

-- ── Commandes ─────────────────────────────────────────────────────────────────
create policy "commandes_select" on public.commandes
  for select using (
    user_id = auth.uid()
    or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );

create policy "commandes_insert" on public.commandes
  for insert with check (auth.uid() = user_id);

create policy "commandes_update_admin" on public.commandes
  for update
  using   (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- ── Lignes de commande ────────────────────────────────────────────────────────
create policy "commande_items_select" on public.commande_items
  for select using (
    exists (
      select 1 from public.commandes c
      where c.id = commande_id
      and (
        c.user_id = auth.uid()
        or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
      )
    )
  );

create policy "commande_items_insert" on public.commande_items
  for insert with check (
    exists (
      select 1 from public.commandes c
      where c.id = commande_id and c.user_id = auth.uid()
    )
  );

-- ── Push tokens ───────────────────────────────────────────────────────────────
create policy "push_tokens_own_all" on public.push_tokens
  for all
  using   (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ── Avis ──────────────────────────────────────────────────────────────────────
create policy "avis_select_public" on public.avis
  for select using (true);

create policy "avis_insert_own" on public.avis
  for insert with check (auth.uid() = user_id);

create policy "avis_update_own" on public.avis
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "avis_delete_own" on public.avis
  for delete using (auth.uid() = user_id);

-- ── Favoris ───────────────────────────────────────────────────────────────────
create policy "favoris_select_own" on public.favoris
  for select using (auth.uid() = user_id);

create policy "favoris_insert_own" on public.favoris
  for insert with check (auth.uid() = user_id);

create policy "favoris_delete_own" on public.favoris
  for delete using (auth.uid() = user_id);


-- =============================================================================
-- 6. STORAGE — Bucket « plats » + politiques
-- =============================================================================

insert into storage.buckets (id, name, public)
values ('plats', 'plats', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "plats_storage_public_read"   on storage.objects;
drop policy if exists "plats_storage_admin_insert"  on storage.objects;
drop policy if exists "plats_storage_admin_update"  on storage.objects;
drop policy if exists "plats_storage_admin_delete"  on storage.objects;

-- Lecture publique (CDN)
create policy "plats_storage_public_read" on storage.objects
  for select using (bucket_id = 'plats');

-- Écriture réservée aux admins
create policy "plats_storage_admin_insert" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'plats'
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );

create policy "plats_storage_admin_update" on storage.objects
  for update to authenticated
  using (
    bucket_id = 'plats'
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  )
  with check (
    bucket_id = 'plats'
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );

create policy "plats_storage_admin_delete" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'plats'
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );


