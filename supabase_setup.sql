create extension if not exists "uuid-ossp";


-- =============================================================================
-- 2. TABLES
-- =============================================================================

-- Profils utilisateurs (liés à auth.users)
create table if not exists public.profiles (
  id        uuid primary key references auth.users (id) on delete cascade,
  nom       text not null default '',
  email     text not null default '',
  telephone text,
  role      text not null default 'user',
  adresse   text
);

-- Catégories de plats
create table if not exists public.categories (
  id   bigint generated by default as identity primary key,
  nom  text   not null,
  emoji text
);

-- Plats du menu
create table if not exists public.plats (
  id          bigint generated by default as identity primary key,
  nom         text             not null,
  description text             not null default '',
  prix        double precision not null default 0,
  image_url   text,
  categorie_id bigint          not null references public.categories (id)
);

-- Commandes
create table if not exists public.commandes (
  id        bigint generated by default as identity primary key,
  user_id   uuid             not null references auth.users (id),
  total     double precision not null,
  statut    text             not null default 'En attente',
  adresse   text             not null default '',
  telephone text             not null default '',
  date      timestamptz default now()
);

-- Lignes de commande
create table if not exists public.commande_items (
  id          bigint generated by default as identity primary key,
  commande_id bigint           not null references public.commandes (id) on delete cascade,
  plat_id     bigint           not null references public.plats (id),
  quantite    int              not null default 1,
  prix        double precision not null
);

-- Tokens FCM pour notifications push
create table if not exists public.push_tokens (
  id         uuid    primary key default gen_random_uuid(),
  user_id    uuid    not null references auth.users (id) on delete cascade,
  token      text    not null,
  platform   text    not null default 'android',
  updated_at timestamptz not null default now(),
  unique (user_id, token)
);

-- Avis (note 1-5 étoiles, un seul avis par utilisateur par plat)
create table if not exists public.avis (
  id      bigint generated by default as identity primary key,
  plat_id bigint not null references public.plats (id)  on delete cascade,
  user_id uuid   not null references auth.users (id)    on delete cascade,
  note    int    not null check (note between 1 and 5),
  date    timestamptz default now(),
  unique (plat_id, user_id)
);

-- Favoris (un favori par utilisateur par plat)
create table if not exists public.favoris (
  id         bigint generated by default as identity primary key,
  user_id    uuid   not null references auth.users (id) on delete cascade,
  plat_id    bigint not null references public.plats (id) on delete cascade,
  created_at timestamptz default now(),
  unique (user_id, plat_id)
);


-- =============================================================================
-- 3. INDEX
-- =============================================================================

create index if not exists idx_commandes_user_id         on public.commandes (user_id);
create index if not exists idx_commande_items_commande_id on public.commande_items (commande_id);
create index if not exists idx_push_tokens_user_id        on public.push_tokens (user_id);
create index if not exists idx_avis_plat_id               on public.avis (plat_id);
create index if not exists idx_favoris_user_id            on public.favoris (user_id);


-- =============================================================================
-- 4. TRIGGER — Création automatique du profil à l'inscription
-- =============================================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nom, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nom', ''),
    coalesce(new.email, '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row
  execute function public.handle_new_user();


